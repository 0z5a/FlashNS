"""Generate the auditable CUDA/HOST scalar transpose from the explicit NS IR."""

from pathlib import Path

from flashns.ns_seed import residual_terms


def header_text():
    lines = ["#pragma once", "// Generated by generate_residual.py; canonical Q10 u,v,p, FP64.",
             "#ifdef __CUDACC__", "#define FLASHNS_V8_HD __host__ __device__ __forceinline__",
             "#else", "#define FLASHNS_V8_HD inline", "#endif", "namespace flashns_v8 {",
             "FLASHNS_V8_HD double residual_seed(const double* z, double w, double nu, double gamma, double* dz) {"]
    terms0, terms1 = residual_terms(0.0), residual_terms(1.0)
    all_terms = []
    for k, (zero, one) in enumerate(zip(terms0, terms1)):
        items = []
        expressions = []
        for (c0, i, j), (c1, i1, j1) in zip(zero, one):
            assert (i, j) == (i1, j1)
            coefficient = f"{float(c0):.17g}" if c0 == c1 else f"({float(c0):.17g}+({float(c1-c0):.17g})*nu)"
            term = f"({coefficient})*z[{i}]" + (f"*z[{j}]" if j >= 0 else "")
            expressions.append(term)
            items.append((coefficient, i, j))
        lines.append(f"  const double r{k} = " + " + ".join(expressions) + ";")
        all_terms.append(items)
    lines.append("  const double loss = 0.5*w*(r0*r0+r1*r1+r2*r2+gamma*(r3*r3+r4*r4+r5*r5+r6*r6+r7*r7+r8*r8));")
    for i in range(30):
        lines.append(f"  dz[{i}] = 0.0;")
    for k, terms in enumerate(all_terms):
        lines.append(f"  const double b{k} = w*" + ("1.0" if k < 3 else "gamma") + f"*r{k};")
        for c, i, j in terms:
            if j < 0:
                lines.append(f"  dz[{i}] += ({c})*b{k};")
            else:
                lines.extend((f"  dz[{i}] += ({c})*b{k}*z[{j}];", f"  dz[{j}] += ({c})*b{k}*z[{i}];"))
    lines.extend(("  return loss;", "}", "}", "#undef FLASHNS_V8_HD", ""))
    return "\n".join(lines)


if __name__ == "__main__":
    path = Path(__file__).with_name("residual_generated.cuh")
    path.write_text(header_text())
    print(path)
